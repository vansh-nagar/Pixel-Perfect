// Inlines public/illustrations/keyboard-iso.svg into src/app/keyboard/keyboard-svg.ts for the /keyboard page,
// split into stacked layers. Run after regenerating the SVG: node scripts/keyboard-svg.mjs
//
// Why layers: one big SVG repaints entirely (masks, clips, ~280 strokes, ~70 skewed legends) every frame
// that ANY key moves, which made the intro lag. Each layer is its own <div><svg> with the same viewBox,
// stacked in painter's order. Static layers paint once and are composited; moving a key repaints only its
// keys layer; whole-layer moves (entrance, cable slide) are compositor-only transforms on the div.
import { readFileSync, writeFileSync } from "node:fs";

const svg = readFileSync("public/illustrations/keyboard-iso.svg", "utf8").trim();
const lines = svg.split("\n");

// root <svg …> open tag (may span lines) and the shared <style> block
const openEnd = lines.findIndex((l) => l.trimEnd().endsWith(">"));
const openTag = lines.slice(0, openEnd + 1).join("\n");
const style = svg.slice(svg.indexOf("<style>"), svg.indexOf("</style>") + "</style>".length);
const label = openTag.match(/aria-label="([^"]*)"/)?.[1] ?? "Keyboard";
const viewBox = openTag.match(/viewBox="([^"]*)"/)[1];

// top-level groups: "  <g id=…" … "  </g>" at two-space indent
const groups = new Map();
for (let i = 0; i < lines.length; i++) {
  const m = lines[i].match(/^ {2}<g id="([^"]+)"/);
  if (!m) continue;
  let j = i;
  while (lines[j] !== "  </g>") j++;
  groups.set(m[1], lines.slice(i, j + 1).join("\n"));
  i = j;
}

// painter's order; `live` layers receive pointer events (hover keys, wheel knobs)
const LAYERS = [
  { name: "cable", ids: ["cable", "switch"] },
  { name: "base", ids: ["case", "well"] },
  { name: "keys", ids: ["keys"], live: true },
  { name: "rim-right", ids: ["case-right"] },
  { name: "controls", ids: ["knob-top", "knob-bottom", "display"], live: true },
  { name: "keys-front", ids: ["keys-front"], live: true },
  { name: "rim-front", ids: ["case-front"] },
];
const used = LAYERS.flatMap((l) => l.ids);
const missing = [...groups.keys()].filter((id) => !used.includes(id));
if (missing.length) throw new Error(`keyboard-svg: top-level groups not assigned to a layer: ${missing.join(", ")}`);

const layerSvg = (l, i) =>
  `<div class="kb-layer" data-layer="${l.name}"${l.live ? " data-live" : ""}>` +
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" class="ill" aria-hidden="true"${i ? ' style="background:transparent"' : ""}>` +
  `${i ? "" : style}${l.ids.map((id) => groups.get(id)).join("\n")}</svg></div>`;

const html = LAYERS.map(layerSvg).join("\n");

writeFileSync(
  "src/app/keyboard/keyboard-svg.ts",
  `// Generated by scripts/keyboard-svg.mjs from public/illustrations/keyboard-iso.svg — do not edit by hand.\n` +
    `export const KEYBOARD_LABEL = ${JSON.stringify(label)};\n` +
    `export const KEYBOARD_LAYERS = ${JSON.stringify(html)};\n`,
);
console.log(`keyboard-svg: ${LAYERS.length} layers, ${groups.size} groups`);
